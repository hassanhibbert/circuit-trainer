create table workout_sessions (
    id            bigint generated by default as identity primary key,
    owner_id      bigint        not null references app_users (id) on delete cascade,
    -- set null so deleting a workout doesn't delete its history
    workout_id    bigint        references workouts (id) on delete set null,
    workout_title varchar(120)  not null,
    completed_at  timestamptz   not null,
    total_seconds integer       not null check (total_seconds between 0 and 86400),
    notes         varchar(2000),
    created_at    timestamptz   not null default now(),
    constraint uq_sessions_owner_title_completed unique (owner_id, workout_title, completed_at)
);

create index idx_sessions_owner_completed_at on workout_sessions (owner_id, completed_at desc);
create index idx_sessions_workout_id on workout_sessions (workout_id);

create table session_sets (
    id               bigint generated by default as identity primary key,
    session_id       bigint        not null references workout_sessions (id) on delete cascade,
    position         integer       not null check (position >= 0),
    exercise_title   varchar(120)  not null,
    set_label        varchar(60),
    reps             integer       check (reps between 0 and 1000),
    weight_lb        numeric(5, 1) check (weight_lb between 0 and 2000),
    duration_seconds integer       check (duration_seconds between 0 and 86400),
    check (reps is not null or weight_lb is not null or duration_seconds is not null)
);

create index idx_session_sets_session_id on session_sets (session_id);
