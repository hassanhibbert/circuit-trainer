create table body_weights (
    id          bigint generated by default as identity primary key,
    owner_id    bigint        not null references app_users (id) on delete cascade,
    measured_on date          not null,
    weight_lb   numeric(5, 1) not null check (weight_lb between 50 and 1000),
    note        varchar(500),
    created_at  timestamptz   not null default now(),
    constraint uq_body_weights_owner_day unique (owner_id, measured_on)
);

create table goals (
    id           bigint generated by default as identity primary key,
    owner_id     bigint        not null references app_users (id) on delete cascade,
    type         varchar(30)   not null check (type in ('TARGET_WEIGHT', 'SESSIONS_PER_WEEK')),
    target_value numeric(6, 1) not null check (target_value > 0),
    start_value  numeric(6, 1) check (start_value > 0),
    start_date   date          not null,
    target_date  date,
    created_at   timestamptz   not null default now(),
    check (target_date is null or target_date >= start_date)
);

create index idx_goals_owner_id on goals (owner_id);
