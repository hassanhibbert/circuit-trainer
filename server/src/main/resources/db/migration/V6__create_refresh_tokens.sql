create table refresh_tokens (
    id         bigint generated by default as identity primary key,
    owner_id   bigint       not null references app_users (id) on delete cascade,
    -- every token from one login shares a family, so a reused one can revoke the whole chain
    family_id  uuid         not null,
    -- sha-256 of the token, the token itself is never stored
    token_hash varchar(64)  not null unique,
    expires_at timestamptz  not null,
    created_at timestamptz  not null default now(),
    used_at    timestamptz,
    revoked_at timestamptz
);

create index idx_refresh_tokens_owner_id on refresh_tokens (owner_id);
create index idx_refresh_tokens_family_id on refresh_tokens (family_id);
create index idx_refresh_tokens_expires_at on refresh_tokens (expires_at);
