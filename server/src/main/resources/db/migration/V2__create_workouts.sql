-- V2: workout definitions. A workout has ordered sections, a section has ordered exercises.
-- Timed workouts (auto-advancing countdowns) and manual workouts (self-paced sets) share
-- this one shape; manual workouts simply have a single untitled section.

create table workouts (
    id                bigint generated by default as identity primary key,
    -- null = built-in: visible to every user, editable by none.
    -- on delete cascade: deleting an account removes its custom workouts with it.
    owner_id          bigint        references app_users (id) on delete cascade,
    title             varchar(120)  not null,
    description       varchar(4000),
    mode              varchar(10)   not null check (mode in ('TIMED', 'MANUAL')),
    sessions_per_week integer       check (sessions_per_week between 1 and 14),
    program_weeks     integer       check (program_weeks between 1 and 52),
    created_at        timestamptz   not null default now(),
    -- A multi-week program needs both numbers, or neither.
    check ((sessions_per_week is null) = (program_weeks is null))
);

create index idx_workouts_owner_id on workouts (owner_id);
-- Partial unique indexes: titles are unique among built-ins, and unique per user
-- (case-insensitively), but two users may both have a workout called "Leg Day".
-- A plain unique(owner_id, title) would not work for built-ins: in SQL, null != null,
-- so any number of rows with owner_id = null would count as "different".
create unique index uq_workouts_builtin_title on workouts (title) where owner_id is null;
create unique index uq_workouts_owner_title on workouts (owner_id, lower(title)) where owner_id is not null;

create table workout_sections (
    id         bigint generated by default as identity primary key,
    workout_id bigint       not null references workouts (id) on delete cascade,
    position   integer      not null check (position >= 0),
    -- Display lines joined with a newline, e.g. 'Round 1' || E'\n' || 'Lower Body & Cardio'.
    title      varchar(200)
);

-- No unique (workout_id, position): when a workout is edited, Hibernate inserts the new
-- rows before it deletes the replaced ones, and a unique position would collide mid-flush.
create index idx_workout_sections_workout_id on workout_sections (workout_id);

create table workout_exercises (
    id               bigint generated by default as identity primary key,
    section_id       bigint       not null references workout_sections (id) on delete cascade,
    position         integer      not null check (position >= 0),
    title            varchar(120) not null,
    modifier         varchar(200),
    set_label        varchar(60),
    -- Free text as shown to the user ("6-8 reps", "Max reps") ...
    reps             varchar(60),
    -- ... plus the number it implies, used to pre-fill the set log.
    target_reps      integer      check (target_reps between 1 and 1000),
    -- Countdown length for timed steps, or a hold timer in manual mode.
    duration_seconds integer      check (duration_seconds between 1 and 3600),
    rest_seconds     integer      check (rest_seconds between 0 and 3600)
);

create index idx_workout_exercises_section_id on workout_exercises (section_id);
