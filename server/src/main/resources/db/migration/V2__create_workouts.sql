create table workouts (
    id                bigint generated by default as identity primary key,
    -- null owner = built-in workout
    owner_id          bigint        references app_users (id) on delete cascade,
    title             varchar(120)  not null,
    description       varchar(4000),
    mode              varchar(10)   not null check (mode in ('TIMED', 'MANUAL')),
    sessions_per_week integer       check (sessions_per_week between 1 and 14),
    program_weeks     integer       check (program_weeks between 1 and 52),
    created_at        timestamptz   not null default now(),
    check ((sessions_per_week is null) = (program_weeks is null))
);

create index idx_workouts_owner_id on workouts (owner_id);
-- unique(owner_id, title) would allow duplicate built-ins since null != null
create unique index uq_workouts_builtin_title on workouts (title) where owner_id is null;
create unique index uq_workouts_owner_title on workouts (owner_id, lower(title)) where owner_id is not null;

create table workout_sections (
    id         bigint generated by default as identity primary key,
    workout_id bigint       not null references workouts (id) on delete cascade,
    position   integer      not null check (position >= 0),
    title      varchar(200)
);

-- no unique (workout_id, position): hibernate inserts new rows before deleting old ones on update
create index idx_workout_sections_workout_id on workout_sections (workout_id);

create table workout_exercises (
    id               bigint generated by default as identity primary key,
    section_id       bigint       not null references workout_sections (id) on delete cascade,
    position         integer      not null check (position >= 0),
    title            varchar(120) not null,
    modifier         varchar(200),
    set_label        varchar(60),
    reps             varchar(60),
    target_reps      integer      check (target_reps between 1 and 1000),
    duration_seconds integer      check (duration_seconds between 1 and 3600),
    rest_seconds     integer      check (rest_seconds between 0 and 3600)
);

create index idx_workout_exercises_section_id on workout_exercises (section_id);
