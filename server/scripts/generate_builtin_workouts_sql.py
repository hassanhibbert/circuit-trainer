#!/usr/bin/env python3
"""
One-off generator for the Flyway seed migration of the built-in workouts.

Reads the workout JSON files the frontend used to bundle (client/src/workouts/*.json)
and prints SQL that inserts them as built-in workouts (owner_id is null).

    python3 server/scripts/generate_builtin_workouts_sql.py \
        > server/src/main/resources/db/migration/V3__seed_builtin_workouts.sql

Once a migration has been applied anywhere it must never change (Flyway checksums it),
so editing a built-in workout later means a NEW migration, not re-running this script.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WORKOUT_DIR = ROOT / "client" / "src" / "workouts"

# Same order as client/src/workouts/index.js, which is the order the list shows them in.
FILES = [
    "30_Beginner_HIIT.json",
    "30_Upper_Strength.json",
    "30_Lower_Strength.json",
    "Manual_Full_Body_Circuit.json",
    "Kettlebell_Month1_Foundation.json",
    "Kettlebell_Month2_Density.json",
    "Kettlebell_Month3_Complexes.json",
]

# "12 reps", "6-8 reps", "10 reps each leg" -> 12, 6, 10. "40-60s carry" and "Max reps" -> null.
TARGET_REPS = re.compile(r"^(\d+)(?:\s*-\s*\d+)?\s+reps\b", re.IGNORECASE)


def lit(value):
    """SQL literal. Single quotes are escaped by doubling them, the standard SQL way."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def duration(unit):
    if "minutes" not in unit and "seconds" not in unit:
        return None
    total = (unit.get("minutes") or 0) * 60 + (unit.get("seconds") or 0)
    return total or None


def target_reps(reps):
    if not reps:
        return None
    match = TARGET_REPS.match(reps.strip())
    return int(match.group(1)) if match else None


def workout_ref(title):
    return f"(select id from workouts where owner_id is null and title = {lit(title)})"


def section_ref(title, position):
    return (f"(select s.id from workout_sections s join workouts w on w.id = s.workout_id "
            f"where w.owner_id is null and w.title = {lit(title)} and s.position = {position})")


def main():
    out = [
        "-- V3: the built-in workouts, generated from the JSON files the frontend used to bundle.",
        "-- Generated by server/scripts/generate_builtin_workouts_sql.py. Do not edit by hand,",
        "-- and never edit after it has been applied: add a new migration instead.",
        "--",
        "-- Built-ins have owner_id = null: every user can read them, nobody can change them.",
        "-- Child rows find their parent by title (unique among built-ins, see V2) rather than",
        "-- by hard-coded id, so the identity sequences stay in charge of id values.",
        "",
    ]
    for file_name in FILES:
        data = json.loads((WORKOUT_DIR / file_name).read_text())
        title = data["title"]
        manual = data.get("type") == "manual"
        mode = "MANUAL" if manual else "TIMED"

        out.append(f"-- {title}")
        out.append(
            "insert into workouts (owner_id, title, description, mode, sessions_per_week, program_weeks) values "
            f"(null, {lit(title)}, {lit(data.get('description'))}, {lit(mode)}, "
            f"{lit(data.get('sessionsPerWeek'))}, {lit(data.get('programWeeks'))});"
        )

        # Manual workouts are a flat list; store them as one untitled section so both
        # modes share a single shape: workout -> sections -> exercises.
        sections = ([{"title": [], "units": data["exercises"]}] if manual else data["sections"])
        for position, section in enumerate(sections):
            section_title = "\n".join(section.get("title") or []) or None
            out.append(
                "insert into workout_sections (workout_id, position, title) values "
                f"({workout_ref(title)}, {position}, {lit(section_title)});"
            )
            rows = []
            for ex_position, unit in enumerate(section["units"]):
                rows.append(
                    f"    ({section_ref(title, position)}, {ex_position}, {lit(unit['title'])}, "
                    f"{lit(unit.get('modifier'))}, {lit(unit.get('setLabel'))}, {lit(unit.get('reps'))}, "
                    f"{lit(target_reps(unit.get('reps')))}, {lit(duration(unit))}, {lit(unit.get('restSeconds'))})"
                )
            out.append(
                "insert into workout_exercises (section_id, position, title, modifier, set_label, reps, "
                "target_reps, duration_seconds, rest_seconds) values\n" + ",\n".join(rows) + ";"
            )
        out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
